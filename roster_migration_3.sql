-- 1) Events pulled from TradingView by the GitHub Action ---------------
create table if not exists econ_events (
  id          text primary key,              -- TradingView event id
  date        timestamptz not null,          -- release time (UTC)
  region      text not null,                 -- US EU JP UK CN AU CA CH NZ HK TW KR IN ID PH MY VN BR
  title       text not null,
  std_name    text not null,                 -- title with any "(Sep)" style period removed
  period      text,                          -- e.g. Sep, Q3, Oct/25
  actual      double precision,
  forecast    double precision,
  previous    double precision,
  unit        text,                          -- %, $, ¥ ...
  scale       text,                          -- K, M, B ...
  importance  int,
  source      text,
  updated_at  timestamptz not null default now()
);
create index if not exists econ_events_date_idx on econ_events (date);

-- 2) Catalog of every indicator seen, with the watchlist flag ----------
create table if not exists econ_catalog (
  region        text not null,
  std_name      text not null,
  watch         boolean not null default false,
  display_name  text,                        -- optional short name (for TRMNL later)
  has_actual    boolean not null default true,
  created_at    timestamptz not null default now(),
  primary key (region, std_name)
);

-- 3) RLS -----------------------------------------------------------------
--    econ_events: read-only for the website. Only the GitHub Action
--    (using the Supabase SECRET key, which bypasses RLS) can write.
--    econ_catalog: website can read and tick/untick watch.
alter table econ_events  enable row level security;
alter table econ_catalog enable row level security;

drop policy if exists econ_events_read    on econ_events;
drop policy if exists econ_catalog_read   on econ_catalog;
drop policy if exists econ_catalog_update on econ_catalog;

create policy econ_events_read    on econ_events  for select to anon, authenticated using (true);
create policy econ_catalog_read   on econ_catalog for select to anon, authenticated using (true);
create policy econ_catalog_update on econ_catalog for update to anon, authenticated using (true) with check (true);

